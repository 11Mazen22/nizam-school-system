#!/bin/sh
# Nizam -- production container entrypoint (Railway/Render/any Docker host).
#
# Responsibilities, in order:
#   1. validate configuration before the web process can accept traffic;
#   2. prepare the persistent mutable-data root;
#   3. write an administrator DB config, migrate + seed under a database-wide
#      advisory lock, and synchronize the nizam_app runtime-role password;
#   4. atomically replace it with the least-privilege runtime DB config;
#   5. verify the runtime identity can really connect;
#   6. start Apache on the platform-assigned port.
#
# No credentials are baked into the image or printed. config/config.php is a
# generated runtime artifact on the persistent data volume, never source.
set -eu
umask 027

DATA_PATH="${NIZAM_DATA_PATH:-/data}"
export NIZAM_DATA_PATH="$DATA_PATH"
MIGRATE_ON_START="${NIZAM_MIGRATE_ON_START:-1}"

required_vars="DB_HOST DB_PORT DB_DATABASE DB_USERNAME DB_PASSWORD"
if [ "$MIGRATE_ON_START" != "0" ]; then
    required_vars="$required_vars DB_ADMIN_HOST DB_ADMIN_PORT DB_ADMIN_DATABASE DB_ADMIN_USERNAME DB_ADMIN_PASSWORD"
fi

missing=""
for var in $required_vars; do
    eval "value=\${$var:-}"
    if [ -z "$value" ]; then
        missing="$missing $var"
    fi
done
if [ -n "$missing" ]; then
    echo "FATAL: missing required environment variable(s):$missing" >&2
    exit 1
fi

# Runtime writes (logs, uploads, backups, sessions and generated config) all
# live under NIZAM_DATA_PATH. Railway mounts a persistent volume at /data;
# the directories are also correct when /data is ordinary host storage.
install -d -m 0750 -o www-data -g www-data \
    "$DATA_PATH/config" \
    "$DATA_PATH/storage/logs" \
    "$DATA_PATH/storage/uploads" \
    "$DATA_PATH/storage/sessions" \
    "$DATA_PATH/database/backups"

# Write config.php atomically from either DB_ADMIN_* or DB_* variables.
# var_export() safely quotes any password content; no shell interpolation ever
# enters PHP source. A same-directory rename keeps readers from observing a
# partially written file.
write_config() {
    prefix="$1"
    CONFIG_PREFIX="$prefix" php -r '
        $prefix = getenv("CONFIG_PREFIX");
        $read = static fn (string $name): string => (string) getenv($prefix . "_" . $name);
        $config = [
            "driver"   => "pgsql",
            "host"     => $read("HOST"),
            "port"     => (int) $read("PORT"),
            "database" => $read("DATABASE"),
            "username" => $read("USERNAME"),
            "password" => $read("PASSWORD"),
            "charset"  => "utf8mb4",
        ];
        $dir = rtrim((string) getenv("NIZAM_DATA_PATH"), "/\\") . "/config";
        $target = $dir . "/config.php";
        $temp = $target . ".tmp";
        $out = "<?php\n/**\n"
            . " * Nizam -- generated by packaging-online/entrypoint.sh.\n"
            . " * Never edit or commit: it is replaced on every container start.\n"
            . " */\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents($temp, $out, LOCK_EX) === false || !rename($temp, $target)) {
            fwrite(STDERR, "FATAL: could not write generated database config.\n");
            exit(1);
        }
        chmod($target, 0640);
    '
    chown root:www-data "$DATA_PATH/config/config.php"
}

if [ "$MIGRATE_ON_START" != "0" ]; then
    echo "Preparing database schema..."
    write_config DB_ADMIN
    php /var/www/html/database/migrate-pg.php
fi

echo "Activating least-privilege database credentials..."
write_config DB

# Fail fast before Apache starts rather than discovering a mistyped reference
# variable on the first user's request. Only the role name is printed.
php -r '
    require "/var/www/html/app/bootstrap.php";
    $pdo = App\Database::connection();
    $role = (string) $pdo->query("SELECT current_user")->fetchColumn();
    if ($role !== "nizam_app") {
        fwrite(STDERR, "FATAL: application connected as an unexpected database role.\n");
        exit(1);
    }
    echo "Database runtime role verified.\n";
'

# One-time official school data. The marker lives on the persistent volume,
# so a later restart never re-imports; the importers are independently
# idempotent as a second guard. Seeding runs with the same least-privilege
# runtime role as the application and must succeed before Apache starts --
# a half-loaded school is worse than a held deployment.
if [ "${NIZAM_SEED_OFFICIAL_DATA:-0}" = "1" ]; then
    SEED_MARKER="$DATA_PATH/storage/official-data-seed.json"
    if [ -f "$SEED_MARKER" ]; then
        echo "Official school data already loaded ($SEED_MARKER)."
    else
        echo "Loading official 2026/2027 school data..."
        # Apache retains the production disable_functions policy. Grant only
        # passthru, and only to this trusted first-boot CLI process, because
        # the seed runner invokes the reviewed importers as isolated PHP
        # children. Those children inherit the normal production policy and
        # do not spawn anything themselves.
        php -d 'disable_functions=exec,shell_exec,system,proc_open,popen' \
            /var/www/html/bin/seed-official-data.php
    fi
fi

# Execute the real dashboard/module read surface with the least-privilege
# production connection. A dialect/schema regression fails this deployment
# before Railway can promote it and send staff into a 500 page.
php /var/www/html/bin/production-smoke.php

# Railway/Render route to the injected PORT. The image itself starts from a
# clean template on every deploy, so @@PORT@@ is present exactly once here.
PORT="${PORT:-80}"
sed -i "s/@@PORT@@/${PORT}/" /etc/apache2/sites-available/000-default.conf
sed -i "s/^Listen 80/Listen ${PORT}/" /etc/apache2/ports.conf

# mod_php is not thread-safe and requires mpm_prefork. Enforce this against
# the live container filesystem immediately before Apache starts; doing it in
# a cached build layer was observed not to stick with the base image.
rm -f /etc/apache2/mods-enabled/mpm_event.load /etc/apache2/mods-enabled/mpm_event.conf \
      /etc/apache2/mods-enabled/mpm_worker.load /etc/apache2/mods-enabled/mpm_worker.conf
if [ ! -e /etc/apache2/mods-enabled/mpm_prefork.load ]; then
    a2enmod mpm_prefork > /dev/null
fi

exec "$@"
