<?php

declare(strict_types=1);

namespace App\Services;

use App\Database;
use PDO;
use RuntimeException;

/**
 * Email notification service using SMTP or PHP's mail().
 *
 * Two transports, picked per send() call:
 *   - SMTP (preferred, and the ONLY one that works on a cloud deployment --
 *     a container has no local MTA and cloud IPs are spam-filtered):
 *     a minimal, dependency-free SMTP client (EHLO/STARTTLS/AUTH LOGIN/
 *     MAIL/RCPT/DATA) -- the same wire protocol PHPMailer speaks, kept
 *     in-house because vendor/ is committed and a school deployment must
 *     never need composer at runtime (composer.json's own docblock).
 *   - PHP mail(), for an offline Windows/XAMPP machine that actually has
 *     an MTA configured -- unchanged behavior there.
 *
 * Configuration comes from config/config.php's 'email' block, with
 * environment variables taking precedence (SMTP_HOST, SMTP_PORT, SMTP_USER,
 * SMTP_PASSWORD, MAIL_FROM_ADDRESS, MAIL_FROM_NAME) so the online deployment
 * -- whose config.php is generated by packaging-online/entrypoint.sh and
 * carries no email keys -- can turn SMTP on from Railway's variable panel
 * without touching the file. SMTP stays disabled until smtp_host is set:
 * automation workflows (birthdays, year reminders) run their checks either
 * way, but with no transport configured the mail is silently skipped.
 */
final class EmailService
{
    private bool $enabled;
    private string $fromEmail;
    private string $fromName;
    private ?string $smtpHost;
    private ?int $smtpPort;
    private ?string $smtpUser;
    private ?string $smtpPassword;
    /** @var 'tls'|'ssl'|'none' */
    private string $smtpEncryption;

    public function __construct()
    {
        // Honor NIZAM_DATA_PATH (the packaged-Windows and container
        // deployments both relocate config/ off the app directory) instead
        // of hardcoding the project root -- found live: the container's
        // config.php lives on /data, and this hardcoded path would have
        // read a file that never exists there.
        $configPath = dataPath() . '/config/config.php';
        /** @var array{email?: array<string, mixed>} $config */
        $config = is_file($configPath) ? require $configPath : [];
        $email = is_array($config) ? ($config['email'] ?? []) : [];
        $email = is_array($email) ? $email : [];

        $env = static function (string $name): ?string {
            $value = getenv($name);
            return is_string($value) && $value !== '' ? $value : null;
        };

        $this->smtpHost = $env('SMTP_HOST') ?? (isset($email['smtp_host']) && is_string($email['smtp_host']) && $email['smtp_host'] !== '' ? $email['smtp_host'] : null);
        $this->smtpPort = (int) ($env('SMTP_PORT') ?? (isset($email['smtp_port']) && $email['smtp_port'] !== null && $email['smtp_port'] !== '' ? $email['smtp_port'] : 0));
        $this->smtpUser = $env('SMTP_USER') ?? (isset($email['smtp_user']) && is_string($email['smtp_user']) && $email['smtp_user'] !== '' ? $email['smtp_user'] : null);
        $this->smtpPassword = $env('SMTP_PASSWORD') ?? (isset($email['smtp_password']) && is_string($email['smtp_password']) && $email['smtp_password'] !== '' ? $email['smtp_password'] : null);
        $this->fromEmail = $env('MAIL_FROM_ADDRESS') ?? (string) ($email['from_email'] ?? 'noreply@school.local');
        $this->fromName = $env('MAIL_FROM_NAME') ?? (string) ($email['from_name'] ?? 'Hadaba Al-Ahram Language School');
        $configuredEncryption = strtolower($env('SMTP_ENCRYPTION') ?? (string) ($email['smtp_encryption'] ?? ''));
        $this->smtpEncryption = in_array($configuredEncryption, ['tls', 'ssl', 'none'], true)
            ? $configuredEncryption
            : ($this->smtpPort === 465 ? 'ssl' : 'tls');
        $this->enabled = ($email['enabled'] ?? false) === true || $this->smtpHost !== null;
    }

    /**
     * Send an email notification
     */
    public function send(string $to, string $subject, string $body, bool $isHtml = true): bool
    {
        if (!$this->enabled) {
            // Silently skip if email is disabled
            return true;
        }

        // Reject newlines as well as malformed addresses before either
        // transport sees them -- prevents SMTP/header injection if a future
        // caller ever passes a value that did not come from a validated user
        // record.
        if (filter_var($to, FILTER_VALIDATE_EMAIL) === false
            || filter_var($this->fromEmail, FILTER_VALIDATE_EMAIL) === false
            || str_contains($subject, "\r")
            || str_contains($subject, "\n")
            || str_contains($this->fromName, "\r")
            || str_contains($this->fromName, "\n")) {
            error_log('[Hadaba] Email send rejected: invalid address or subject');
            return false;
        }

        if ($this->smtpHost !== null) {
            return $this->sendSmtp($to, $subject, $body, $isHtml);
        }

        // Offline fallback: an MTA exists on the local machine.
        $headers = [
            'From: ' . $this->fromName . ' <' . $this->fromEmail . '>',
            'Reply-To: ' . $this->fromEmail,
            'X-Mailer: PHP/' . phpversion(),
        ];

        if ($isHtml) {
            $headers[] = 'MIME-Version: 1.0';
            $headers[] = 'Content-Type: text/html; charset=UTF-8';
        }

        return mail($to, $subject, $body, implode("\r\n", $headers));
    }

    /**
     * Minimal SMTP client: enough of RFC 5321 for one message over one
     * connection -- greeting, EHLO, optional STARTTLS (implicit TLS on 465),
     * optional AUTH LOGIN, one MAIL FROM / RCPT TO / DATA transaction.
     * Every failure path returns false (logging the reason to error_log,
     * which reaches the platform's log capture) -- a notification that
     * cannot be delivered must never take the request that triggered it
     * down with it.
     */
    private function sendSmtp(string $to, string $subject, string $body, bool $isHtml): bool
    {
        $host = (string) $this->smtpHost;
        $port = $this->smtpPort > 0 ? $this->smtpPort : 587;

        $context = stream_context_create(['ssl' => [
            'verify_peer' => true,
            'verify_peer_name' => true,
            'peer_name' => $host,
            'SNI_enabled' => true,
            'allow_self_signed' => false,
        ]]);
        $socket = @stream_socket_client(
            ($this->smtpEncryption === 'ssl' ? 'ssl://' : 'tcp://') . $host . ':' . $port,
            $errno,
            $errstr,
            15,
            STREAM_CLIENT_CONNECT,
            $context
        );
        if ($socket === false) {
            error_log("[Hadaba] SMTP connect failed: {$errstr} ({$errno})");
            return false;
        }
        stream_set_timeout($socket, 15);

        try {
            self::smtpExpect($socket, '220', 'greeting');

            self::smtpCommand($socket, 'EHLO nizam.local', '250', 'EHLO');
            if ($this->smtpEncryption === 'tls') {
                self::smtpCommand($socket, 'STARTTLS', '220', 'STARTTLS');
                if (!stream_socket_enable_crypto($socket, true, STREAM_CRYPTO_METHOD_TLS_CLIENT)) {
                    error_log('[Hadaba] SMTP TLS negotiation failed');
                    return false;
                }
                self::smtpCommand($socket, 'EHLO nizam.local', '250', 'EHLO after TLS');
            }

            if ($this->smtpUser !== null && $this->smtpPassword !== null) {
                // Never send credentials over cleartext by accident. A user
                // who deliberately needs a trusted LAN relay without AUTH can
                // use SMTP_ENCRYPTION=none and leave the credentials empty.
                if ($this->smtpEncryption === 'none') {
                    throw new RuntimeException('refusing AUTH over an unencrypted connection');
                }
                self::smtpCommand($socket, 'AUTH LOGIN', '334', 'AUTH');
                self::smtpCommand($socket, base64_encode($this->smtpUser), '334', 'AUTH username');
                self::smtpCommand($socket, base64_encode($this->smtpPassword), '235', 'AUTH password');
            }

            self::smtpCommand($socket, 'MAIL FROM:<' . $this->fromEmail . '>', '250', 'MAIL FROM');
            self::smtpCommand($socket, 'RCPT TO:<' . $to . '>', '250', 'RCPT TO');
            self::smtpCommand($socket, 'DATA', '354', 'DATA');

            // RFC 5321 dot-stuffing: a body line starting with "." gets a
            // second "." so the lone "." terminator can never appear inside
            // the message.
            $payload = preg_replace('/^\\./m', '..', $body) ?? $body;
            $encodedFromName = function_exists('mb_encode_mimeheader')
                ? mb_encode_mimeheader($this->fromName, 'UTF-8', 'B')
                : $this->fromName;
            $headers = [
                'From: ' . $encodedFromName . ' <' . $this->fromEmail . '>',
                'To: <' . $to . '>',
                'Subject: ' . (function_exists('mb_encode_mimeheader') ? mb_encode_mimeheader($subject, 'UTF-8', 'B') : $subject),
                'Date: ' . date(DATE_RFC2822),
                'Message-ID: <' . bin2hex(random_bytes(16)) . '@nizam.local>',
                'MIME-Version: 1.0',
                'Content-Type: text/html; charset=UTF-8',
                'Content-Transfer-Encoding: 8bit',
                'X-Mailer: Nizam-School-System',
            ];
            if (!$isHtml) {
                $headers[6] = 'Content-Type: text/plain; charset=UTF-8';
            }
            fwrite($socket, implode("\r\n", $headers) . "\r\n\r\n" . $payload . "\r\n.\r\n");
            self::smtpExpect($socket, '250', 'message acceptance');

            fwrite($socket, "QUIT\r\n");
            return true;
        } catch (RuntimeException $e) {
            error_log('[Hadaba] SMTP send failed: ' . $e->getMessage());
            return false;
        } finally {
            fclose($socket);
        }
    }

    /** Reads one full SMTP reply (multiline replies end at "NNN "), enforcing the expected code. */
    private static function smtpExpect($socket, string $expected, string $stage): void
    {
        $lines = [];
        $line = '';
        do {
            $line = fgets($socket, 1024);
            if ($line === false) {
                throw new RuntimeException("{$stage}: connection lost");
            }
            $lines[] = trim($line);
            // A reply line is "NNN text" when final, "NNN-text" when another
            // line of the same reply follows.
        } while (strlen($line) < 4 || $line[3] === '-');

        if (!str_starts_with((string) $lines[0], $expected)) {
            throw new RuntimeException("{$stage}: expected {$expected}, got: " . implode(' | ', $lines));
        }
    }

    private static function smtpCommand($socket, string $command, string $expected, string $stage): void
    {
        fwrite($socket, $command . "\r\n");
        self::smtpExpect($socket, $expected, $stage);
    }

    /**
     * Send notification to admin users
     */
    public function notifyAdmins(string $subject, string $body): void
    {
        $pdo = Database::connection();
        $stmt = $pdo->query("
            SELECT u.email, u.full_name 
            FROM users u
            JOIN roles r ON u.role_id = r.id
            WHERE r.code = 'admin' AND u.is_active = 1 AND u.email IS NOT NULL AND u.email != ''
        ");
        
        while ($admin = $stmt->fetch(PDO::FETCH_ASSOC)) {
            $personalizedBody = str_replace('{name}', $admin['full_name'], $body);
            $this->send($admin['email'], $subject, $personalizedBody);
        }
    }

    /**
     * Send birthday notification
     */
    public function sendBirthdayNotification(array $student): void
    {
        $subject = __('email.birthday_subject', ['name' => $student['full_name']]);
        $body = $this->renderTemplate('birthday', [
            'student_name' => $student['full_name'],
            'student_code' => $student['student_code'],
            'grade' => $student['grade_name'],
            'class' => $student['class_name'],
        ]);

        // Send to admins and staff
        $this->notifyAdmins($subject, $body);
    }

    /**
     * Send year rollover reminder
     */
    public function sendYearRolloverReminder(array $currentYear, int $daysUntilEnd): void
    {
        $subject = __('email.year_ending_subject', ['days' => $daysUntilEnd]);
        $body = $this->renderTemplate('year_rollover', [
            'year_label' => $currentYear['label'],
            'days_remaining' => $daysUntilEnd,
            'end_date' => $currentYear['end_date'],
        ]);

        $this->notifyAdmins($subject, $body);
    }

    /**
     * Send backup notification
     */
    public function sendBackupNotification(bool $success, string $filename, ?string $error = null): void
    {
        $subject = $success 
            ? __('email.backup_success_subject')
            : __('email.backup_failed_subject');
        
        $body = $this->renderTemplate('backup', [
            'success' => $success,
            'filename' => $filename,
            'error' => $error,
            'time' => date('Y-m-d H:i:s'),
        ]);

        $this->notifyAdmins($subject, $body);
    }

    /**
     * Send report generation notification
     */
    public function sendReportGeneratedNotification(string $reportName, string $downloadUrl, string $generatedBy): void
    {
        $subject = __('email.report_ready_subject', ['report' => $reportName]);
        $body = $this->renderTemplate('report', [
            'report_name' => $reportName,
            'download_url' => $downloadUrl,
            'generated_by' => $generatedBy,
            'generated_at' => date('Y-m-d H:i:s'),
        ]);

        $this->notifyAdmins($subject, $body);
    }

    /**
     * Render an email template
     */
    private function renderTemplate(string $template, array $data): string
    {
        $templatePath = dirname(__DIR__, 2) . "/views/emails/{$template}.php";
        
        if (!file_exists($templatePath)) {
            // Fallback to simple text template
            return $this->renderSimpleTemplate($template, $data);
        }

        ob_start();
        extract($data);
        require $templatePath;
        return ob_get_clean();
    }

    /**
     * Simple text template fallback
     */
    private function renderSimpleTemplate(string $template, array $data): string
    {
        switch ($template) {
            case 'birthday':
                return "
                    <h2>🎂 Student Birthday Today!</h2>
                    <p><strong>{$data['student_name']}</strong> (Code: {$data['student_code']}) is celebrating their birthday today!</p>
                    <p>Grade: {$data['grade']} - Class: {$data['class']}</p>
                    <p>Consider sending them a birthday wish!</p>
                ";

            case 'year_rollover':
                return "
                    <h2>⚠️ Academic Year Ending Soon</h2>
                    <p>The current academic year <strong>{$data['year_label']}</strong> will end in <strong>{$data['days_remaining']} days</strong>.</p>
                    <p>End Date: {$data['end_date']}</p>
                    <p>Please prepare for:</p>
                    <ul>
                        <li>Student promotions</li>
                        <li>Creating the next academic year</li>
                        <li>Year rollover process</li>
                    </ul>
                ";

            case 'backup':
                if ($data['success']) {
                    return "
                        <h2>✅ Backup Completed Successfully</h2>
                        <p>A database backup was created successfully.</p>
                        <p><strong>Filename:</strong> {$data['filename']}</p>
                        <p><strong>Time:</strong> {$data['time']}</p>
                    ";
                } else {
                    return "
                        <h2>❌ Backup Failed</h2>
                        <p>The scheduled database backup failed.</p>
                        <p><strong>Error:</strong> {$data['error']}</p>
                        <p><strong>Time:</strong> {$data['time']}</p>
                        <p>Please check the system logs and try again.</p>
                    ";
                }

            case 'report':
                return "
                    <h2>📊 Report Generated</h2>
                    <p>The report <strong>{$data['report_name']}</strong> has been generated.</p>
                    <p><strong>Generated by:</strong> {$data['generated_by']}</p>
                    <p><strong>Time:</strong> {$data['generated_at']}</p>
                    <p><a href='{$data['download_url']}'>Download Report</a></p>
                ";

            default:
                return "Notification from Hadaba Al-Ahram Language School";
        }
    }
}
