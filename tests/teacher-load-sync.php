<?php

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

/**
 * Teaching-load sync against a throwaway MySQL database.
 *
 * The HTTP suite talks to a server subprocess, so it cannot call a service
 * that opens the application's own Database::connection(). This test builds a
 * disposable database, points NIZAM_DATA_PATH at a matching temporary config,
 * and exercises TeacherAssignmentSyncService directly:
 *
 *  - a printed triple with no assignment creates one with weekly_periods equal
 *    to its cells and source 'timetable';
 *  - a later grid change corrects a derived load;
 *  - a load created or edited on the assignment screen (source 'manual') is
 *    never overwritten, even when the grid disagrees.
 */

$root = dirname(__DIR__);
$passed = 0;
$failed = 0;
$failures = [];

function check(bool $condition, string $label): void
{
    global $passed, $failed, $failures;
    if ($condition) {
        $passed++;
        fwrite(STDOUT, "  ok    {$label}\n");
        return;
    }
    $failed++;
    $failures[] = $label;
    fwrite(STDOUT, "  FAIL  {$label}\n");
}

function removeTree(string $path): void
{
    if (!is_dir($path)) {
        return;
    }
    foreach (scandir($path) ?: [] as $item) {
        if ($item === '.' || $item === '..') {
            continue;
        }
        $child = $path . DIRECTORY_SEPARATOR . $item;
        is_dir($child) ? removeTree($child) : @unlink($child);
    }
    @rmdir($path);
}

$sourceConfig = require $root . '/config/config.php';
$driver = $sourceConfig['driver'] ?? 'mysql';
if ($driver !== 'mysql') {
    fwrite(STDERR, "BLOCKED: this test needs a disposable MySQL/MariaDB server (driver is {$driver}).\n");
    exit(2);
}

$suffix = bin2hex(random_bytes(4));
$database = 'nizam_load_test_' . $suffix;
$tempPath = rtrim(sys_get_temp_dir(), '/\\') . DIRECTORY_SEPARATOR . 'nizam-load-' . $suffix;
$testConfig = $sourceConfig;
$testConfig['database'] = $database;

mkdir($tempPath . '/config', 0777, true);
mkdir($tempPath . '/storage/logs', 0777, true);
mkdir($tempPath . '/storage/uploads', 0777, true);
file_put_contents(
    $tempPath . '/config/config.php',
    "<?php\n// Generated by tests/teacher-load-sync.php. Not committed.\nreturn " . var_export($testConfig, true) . ";\n"
);

// The application's Database class reads dataPath(), which honours this
// variable, so every service in this process uses the throwaway database.
putenv('NIZAM_DATA_PATH=' . $tempPath);
$_SERVER['NIZAM_DATA_PATH'] = $tempPath;

require $root . '/app/bootstrap.php';

$dsn = sprintf(
    'mysql:host=%s;port=%d;charset=%s',
    $testConfig['host'],
    $testConfig['port'],
    $testConfig['charset'] ?? 'utf8mb4'
);

$base = new PDO($dsn, $testConfig['username'], $testConfig['password'], [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
]);
$base->exec("CREATE DATABASE `{$database}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");

$pdo = null;

try {
    $pdo = App\Database::connection();
    $pdo->exec("USE `{$database}`");

    $migration = new App\Services\MigrationService();
    $result = $migration->run($pdo, $root . '/database/migrations');
    if ($result['failure'] !== null) {
        fwrite(STDERR, "BLOCKED: migration {$result['failure']['migration']} failed: {$result['failure']['error']}\n");
        exit(2);
    }

    $seeds = new App\Services\SeedService();
    $seedResult = $seeds->run($pdo, $root . '/database/seeds');
    if ($seedResult['failure'] !== null) {
        fwrite(STDERR, "BLOCKED: seed {$seedResult['failure']['seed']} failed: {$seedResult['failure']['error']}\n");
        exit(2);
    }

    $yearId = (int) $pdo->query("SELECT id FROM academic_years WHERE is_active = 1 LIMIT 1")->fetchColumn();
    $gradeId = (int) $pdo->query('SELECT id FROM grades ORDER BY sort_order LIMIT 1')->fetchColumn();
    check($yearId > 0 && $gradeId > 0, 'Seeded an active year and a grade');

    $pdo->prepare('INSERT INTO classes (grade_id, academic_year_id, name, capacity, is_active) VALUES (?, ?, ?, 30, 1)')
        ->execute([$gradeId, $yearId, 'TL1']);
    $classId = (int) $pdo->lastInsertId();

    $subjectA = 0;
    $subjectB = 0;
    foreach ([['TLA', 'Load Test A', 'اختبار الحمل أ'], ['TLB', 'Load Test B', 'اختبار الحمل ب']] as [$code, $en, $ar]) {
        $pdo->prepare('INSERT INTO subjects (code, name_en, name_ar, is_active) VALUES (?, ?, ?, 1)')
            ->execute([$code, $en, $ar]);
        if ($subjectA === 0) {
            $subjectA = (int) $pdo->lastInsertId();
        } else {
            $subjectB = (int) $pdo->lastInsertId();
        }
    }

    $pdo->prepare("INSERT INTO teachers (teacher_code, full_name, status) VALUES ('TCH-TL', 'Load Teacher', 'active')")
        ->execute();
    $teacherId = (int) $pdo->lastInsertId();

    $slot = $pdo->prepare(
        'INSERT INTO timetables (academic_year_id, class_id, day_of_week, period_number, subject_id, teacher_id)
         VALUES (:year, :class, :day, :period, :subject, :teacher)'
    );
    $addSlot = static function (int $day, int $period, int $subjectId) use ($slot, $yearId, $classId, $teacherId): void {
        $slot->execute([
            'year' => $yearId, 'class' => $classId, 'day' => $day,
            'period' => $period, 'subject' => $subjectId, 'teacher' => $teacherId,
        ]);
    };

    // Two printed cells for subject A, one for subject B.
    $addSlot(2, 1, $subjectA);
    $addSlot(3, 1, $subjectA);
    $addSlot(4, 1, $subjectB);

    $assignments = new App\Services\AssignmentService();
    $manualId = $assignments->create($teacherId, $subjectA, $classId, $yearId, 5);
    $assignments->update($manualId, 6);

    fwrite(STDOUT, "\nManual load protection\n");
    $source = $pdo->query("SELECT weekly_periods, weekly_periods_source FROM teacher_assignments WHERE id = {$manualId}")->fetch();
    check((int) $source['weekly_periods'] === 6, 'An edit on the assignment screen saves the new periods');
    check($source['weekly_periods_source'] === 'manual', 'An edited assignment is marked manual');

    $sync = new App\Services\TeacherAssignmentSyncService();
    $first = $sync->sync($yearId);
    check($first['manual_kept'] === 1, 'The sync keeps the hand-edited load');
    check($first['created'] === 1, 'The sync creates the missing assignment');
    check($first['updated'] === 0, 'The sync corrects nothing on its first pass');

    $manualAfter = (int) $pdo->query("SELECT weekly_periods FROM teacher_assignments WHERE id = {$manualId}")->fetchColumn();
    check($manualAfter === 6, 'The hand-edited periods are unchanged (6, not the grid\'s 2)');

    fwrite(STDOUT, "\nDerived load correction\n");
    $derived = $pdo->query("SELECT weekly_periods, weekly_periods_source FROM teacher_assignments WHERE teacher_id = {$teacherId} AND subject_id = {$subjectB}")->fetch();
    check((int) $derived['weekly_periods'] === 1, 'A derived assignment starts with the printed cell count');
    check($derived['weekly_periods_source'] === 'timetable', 'A derived assignment is marked timetable');

    $addSlot(5, 1, $subjectB);
    $second = $sync->sync($yearId);
    check($second['updated'] === 1, 'A grid change corrects the derived load');
    check($second['manual_kept'] === 1, 'The hand-edited load is still kept on the second pass');

    $derivedAfter = (int) $pdo->query("SELECT weekly_periods FROM teacher_assignments WHERE teacher_id = {$teacherId} AND subject_id = {$subjectB}")->fetchColumn();
    check($derivedAfter === 2, 'The derived load now equals its two printed cells');

    $third = $sync->sync($yearId);
    check($third['created'] === 0 && $third['updated'] === 0, 'A repeat sync changes nothing');

    $links = (int) $pdo->query("SELECT COUNT(*) FROM teacher_subjects WHERE teacher_id = {$teacherId}")->fetchColumn();
    check($links === 2, 'Both teaching pairs are linked to the teacher');
} finally {
    try {
        $base->exec("DROP DATABASE IF EXISTS `{$database}`");
    } catch (Throwable) {
        // Leave the disposable database to be removed with the temp folder.
    }
    $pdo = null;
    removeTree($tempPath);
}

fwrite(STDOUT, "\n" . str_repeat('-', 60) . "\n");
if ($failed === 0) {
    fwrite(STDOUT, "Teaching-load sync: {$passed} passed, 0 failed\n");
    exit(0);
}

fwrite(STDOUT, "Teaching-load sync: {$passed} passed, {$failed} failed\n");
foreach ($failures as $failure) {
    fwrite(STDOUT, "  - {$failure}\n");
}
exit(1);
