<?php

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

/**
 * PostgreSQL parity test against a disposable server.
 *
 * The MySQL suite cannot prove the pgsql branches of the new repositories.
 * Point this at a throwaway PostgreSQL instance (never a school database):
 *
 *   NIZAM_PG_HOST=127.0.0.1 NIZAM_PG_PORT=55432 \
 *   NIZAM_PG_USER=postgres NIZAM_PG_PASSWORD= \
 *   php tests/postgres-parity.php
 *
 * It creates a uniquely named database, applies the real
 * database/migrations-pg set and seeds, then exercises:
 *
 *  - migration 029 (roster verification, aliases, gaps) and 030 (load source);
 *  - RosterVerificationRepository::save twice (ON CONFLICT update);
 *  - TeacherAliasRepository::attach twice (ON CONFLICT update);
 *  - TimetableGapRepository::upsert twice, including status preservation;
 *  - the teaching-load sync and its manual-edit protection on PostgreSQL.
 *
 * It drops that database and its temporary data path when it finishes.
 *
 * A disposable embedded server can be started with the project-local
 * binaries documented in README ("PostgreSQL parity"):
 *   npm install --no-save @embedded-postgres/windows-x64
 */

$root = dirname(__DIR__);
$passed = 0;
$failed = 0;
$failures = [];

function check(bool $condition, string $label): void
{
    global $passed, $failed, $failures;
    if ($condition) {
        $passed++;
        fwrite(STDOUT, "  ok    {$label}\n");
        return;
    }
    $failed++;
    $failures[] = $label;
    fwrite(STDOUT, "  FAIL  {$label}\n");
}

function removeTree(string $path): void
{
    if (!is_dir($path)) {
        return;
    }
    foreach (scandir($path) ?: [] as $item) {
        if ($item === '.' || $item === '..') {
            continue;
        }
        $child = $path . DIRECTORY_SEPARATOR . $item;
        is_dir($child) ? removeTree($child) : @unlink($child);
    }
    @rmdir($path);
}

$host = getenv('NIZAM_PG_HOST') ?: '127.0.0.1';
$port = (int) (getenv('NIZAM_PG_PORT') ?: 55432);
$user = getenv('NIZAM_PG_USER') ?: 'postgres';
$password = getenv('NIZAM_PG_PASSWORD') ?: '';

try {
    $admin = new PDO(
        sprintf('pgsql:host=%s;port=%d;dbname=postgres', $host, $port),
        $user,
        $password,
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC]
    );
} catch (Throwable $e) {
    fwrite(STDERR, "BLOCKED: no disposable PostgreSQL at {$host}:{$port} ({$e->getMessage()}).\n");
    fwrite(STDERR, "Start one first; this test never targets the school database.\n");
    exit(2);
}

$suffix = bin2hex(random_bytes(4));
$database = 'nizam_pg_test_' . $suffix;
$tempPath = rtrim(sys_get_temp_dir(), '/\\') . DIRECTORY_SEPARATOR . 'nizam-pg-' . $suffix;
$admin->exec('CREATE DATABASE ' . $database);

// Point the application's own connection at the disposable database before
// any service is constructed.
$config = [
    'driver' => 'pgsql',
    'host' => $host,
    'port' => $port,
    'database' => $database,
    'username' => $user,
    'password' => $password,
    'charset' => 'utf8mb4',
];
mkdir($tempPath . '/config', 0777, true);
mkdir($tempPath . '/storage/logs', 0777, true);
mkdir($tempPath . '/storage/uploads', 0777, true);
file_put_contents(
    $tempPath . '/config/config.php',
    "<?php\n// Generated by tests/postgres-parity.php. Not committed.\nreturn " . var_export($config, true) . ";\n"
);
putenv('NIZAM_DATA_PATH=' . $tempPath);
$_SERVER['NIZAM_DATA_PATH'] = $tempPath;

require $root . '/app/bootstrap.php';

try {
    $pdo = App\Database::connection();
    $pdo->exec('SET search_path TO public');

    fwrite(STDOUT, "Disposable PostgreSQL\n");
    $migration = new App\Services\MigrationService();
    $migrated = $migration->run($pdo, $root . '/database/migrations-pg');
    check($migrated['failure'] === null, 'All PostgreSQL migrations apply (including 029 and 030)');
    if ($migrated['failure'] !== null) {
        throw new RuntimeException('migration: ' . $migrated['failure']['migration'] . ' -- ' . $migrated['failure']['error']);
    }

    $seeds = new App\Services\SeedService();
    $seeded = $seeds->run($pdo, $root . '/database/seeds-pg');
    check($seeded['failure'] === null, 'All PostgreSQL seeds apply');

    $columns = $pdo->query("SELECT column_name FROM information_schema.columns WHERE table_name = 'teacher_assignments'")->fetchAll(PDO::FETCH_COLUMN);
    check(in_array('weekly_periods_source', $columns, true), 'Migration 030 adds the load-source column');
    $tables = $pdo->query("SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'")->fetchAll(PDO::FETCH_COLUMN);
    foreach (['roster_verifications', 'teacher_aliases', 'timetable_gaps'] as $table) {
        check(in_array($table, $tables, true), "Migration 029 creates {$table}");
    }

    $yearId = (int) $pdo->query('SELECT id FROM academic_years WHERE is_active = 1 LIMIT 1')->fetchColumn();
    $gradeId = (int) $pdo->query('SELECT id FROM grades ORDER BY sort_order LIMIT 1')->fetchColumn();
    check($yearId > 0 && $gradeId > 0, 'Seeds provide an active year and a grade');

    // PostgreSQL mirrors the MySQL SMALLINT flags, not booleans.
    $pdo->prepare('INSERT INTO classes (grade_id, academic_year_id, name, capacity, is_active) VALUES (?, ?, ?, 30, 1) RETURNING id')
        ->execute([$gradeId, $yearId, 'PG1']);
    $classId = (int) $pdo->query("SELECT id FROM classes WHERE name = 'PG1'")->fetchColumn();

    $pdo->prepare("INSERT INTO teachers (teacher_code, full_name, status) VALUES ('TCH-PG', 'PG Teacher', 'active') RETURNING id")
        ->execute();
    $teacherId = (int) $pdo->query("SELECT id FROM teachers WHERE teacher_code = 'TCH-PG'")->fetchColumn();

    $subjectIds = [];
    foreach ([['PGA', 'PG Subject A', 'مادة أ'], ['PGB', 'PG Subject B', 'مادة ب']] as [$code, $en, $ar]) {
        $pdo->prepare('INSERT INTO subjects (code, name_en, name_ar, is_active) VALUES (?, ?, ?, 1) RETURNING id')
            ->execute([$code, $en, $ar]);
        $subjectIds[$code] = (int) $pdo->query("SELECT id FROM subjects WHERE code = '{$code}'")->fetchColumn();
    }

    fwrite(STDOUT, "\nCross-driver upserts\n");
    $verifications = new App\Repositories\RosterVerificationRepository();
    $verifications->save($classId, $yearId, 20, str_repeat('a', 64), 'first', null);
    $verifications->save($classId, $yearId, 21, str_repeat('b', 64), 'second', null);
    $saved = $pdo->query('SELECT COUNT(*) AS c, MAX(student_count) AS n, MAX(fingerprint) AS f FROM roster_verifications')->fetch();
    check((int) $saved['c'] === 1, 'Roster verification save updates instead of duplicating');
    check((int) $saved['n'] === 21, 'The verification upsert writes the new count');
    check($saved['f'] === str_repeat('b', 64), 'The verification upsert writes the new fingerprint');

    $aliases = new App\Repositories\TeacherAliasRepository();
    $aliases->attach($teacherId, 'PG Printed', 'timetable');
    $aliases->attach($teacherId, 'PG Printed', 'roster');
    $alias = $pdo->query('SELECT COUNT(*) AS c, MAX(source) AS s FROM teacher_aliases')->fetch();
    check((int) $alias['c'] === 1, 'Teacher alias attach updates instead of duplicating');
    check($alias['s'] === 'roster', 'The alias upsert writes the new source');

    $gaps = new App\Repositories\TimetableGapRepository();
    $gaps->upsert($yearId, $classId, 2, 1, $subjectIds['PGA'], 'مادة أ', 'PG Printed', 'no_teacher', 'doc', 'open');
    $gap = $pdo->query('SELECT COUNT(*) AS c, MAX(status) AS s FROM timetable_gaps')->fetch();
    check((int) $gap['c'] === 1, 'Timetable gap upsert updates instead of duplicating');
    check($gap['s'] === 'open', 'A new gap starts open');
    // The real resolution path, then a re-sync: resolving also creates the
    // lesson in production, but the status update is what this proves here.
    $gaps->resolveSlot($yearId, $classId, 2, 1, $teacherId, $subjectIds['PGA'], 0);
    check($pdo->query('SELECT status FROM timetable_gaps')->fetchColumn() === 'resolved', 'Resolving a gap writes the resolved status');
    $gaps->upsert($yearId, $classId, 2, 1, $subjectIds['PGA'], 'مادة أ', 'PG Printed', 'no_teacher', 'doc', 'open');
    check($pdo->query('SELECT status FROM timetable_gaps')->fetchColumn() === 'resolved', 'A re-sync keeps a resolved gap resolved');

    fwrite(STDOUT, "\nTeaching load on PostgreSQL\n");
    $slot = $pdo->prepare('INSERT INTO timetables (academic_year_id, class_id, day_of_week, period_number, subject_id, teacher_id) VALUES (?, ?, ?, ?, ?, ?)');
    $slot->execute([$yearId, $classId, 2, 1, $subjectIds['PGA'], $teacherId]);
    $slot->execute([$yearId, $classId, 3, 1, $subjectIds['PGA'], $teacherId]);
    $slot->execute([$yearId, $classId, 4, 1, $subjectIds['PGB'], $teacherId]);

    $assignments = new App\Services\AssignmentService();
    $manualId = $assignments->create($teacherId, $subjectIds['PGA'], $classId, $yearId, 5);
    $assignments->update($manualId, 6);

    $sync = new App\Services\TeacherAssignmentSyncService();
    $first = $sync->sync($yearId);
    check($first['manual_kept'] === 1, 'The sync keeps a hand-edited load on PostgreSQL');
    check($first['created'] === 1, 'The sync creates a derived assignment on PostgreSQL');
    check((int) $pdo->query("SELECT weekly_periods FROM teacher_assignments WHERE id = {$manualId}")->fetchColumn() === 6, 'The manual load is not overwritten');
    check($pdo->query("SELECT weekly_periods_source FROM teacher_assignments WHERE id = {$manualId}")->fetchColumn() === 'manual', 'The manual load stays marked manual');

    $slot->execute([$yearId, $classId, 5, 1, $subjectIds['PGB'], $teacherId]);
    $second = $sync->sync($yearId);
    check($second['updated'] === 1, 'The sync corrects a derived load on PostgreSQL');
} catch (Throwable $e) {
    $failed++;
    $failures[] = 'exception: ' . $e->getMessage();
    fwrite(STDOUT, '  FAIL  exception: ' . $e->getMessage() . "\n");
} finally {
    try {
        $admin->exec('SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = ' . $admin->quote($database));
        $admin->exec('DROP DATABASE IF EXISTS ' . $database);
    } catch (Throwable) {
        // The database is disposable; the operator can drop it if this fails.
    }
    removeTree($tempPath);
}

fwrite(STDOUT, "\n" . str_repeat('-', 60) . "\n");
if ($failed === 0) {
    fwrite(STDOUT, "PostgreSQL parity: {$passed} passed, 0 failed\n");
    exit(0);
}

fwrite(STDOUT, "PostgreSQL parity: {$passed} passed, {$failed} failed\n");
foreach ($failures as $failure) {
    fwrite(STDOUT, "  - {$failure}\n");
}
exit(1);
