<?php

declare(strict_types=1);

/**
 * Nizam -- official school data seed test.
 *
 * Builds a throwaway MySQL database from the real migrations and seeds, points
 * a throwaway data path at it, then runs bin/seed-official-data.php exactly as
 * the production entrypoint does. Asserts the school's actual counts, runs the
 * importers a second time to prove idempotency, and proves the marker prevents
 * an unnecessary third run. Nothing in the real school database is touched.
 */

$root = dirname(__DIR__);
require $root . '/app/bootstrap.php';
restore_exception_handler();

use App\Services\MigrationService;
use App\Services\SeedService;

$passed = 0;
$failed = 0;

function seedCheck(bool $condition, string $label, string $detail = ''): void
{
    global $passed, $failed;
    if ($condition) {
        $passed++;
        echo "  ok    {$label}\n";
        return;
    }
    $failed++;
    echo "  FAIL  {$label}" . ($detail !== '' ? " -- {$detail}" : '') . "\n";
}

/**
 * @param list<string> $arguments
 * @return array{status:int, output:string}
 */
function runSeedCommand(array $arguments, string $dataPath): array
{
    $root = dirname(__DIR__);
    $log = tempnam(sys_get_temp_dir(), 'nizam-seed-');
    if ($log === false) {
        throw new RuntimeException('Could not create a seed log.');
    }
    $descriptors = [
        0 => ['file', 'NUL', 'r'],
        1 => ['file', $log, 'w'],
        2 => ['file', $log, 'a'],
    ];
    if (DIRECTORY_SEPARATOR === '/') {
        $descriptors[0] = ['file', '/dev/null', 'r'];
    }
    $env = getenv();
    if (!is_array($env)) {
        $env = [];
    }
    $env['NIZAM_DATA_PATH'] = $dataPath;
    $env['PATH'] = getenv('PATH') ?: '';
    // Match the production entrypoint exactly: web PHP keeps every process
    // function disabled, while this trusted CLI runner receives passthru only
    // so it can invoke each importer in an isolated PHP process.
    $process = proc_open(
        array_merge([
            PHP_BINARY,
            '-d',
            'disable_functions=exec,shell_exec,system,proc_open,popen',
        ], $arguments),
        $descriptors,
        $pipes,
        $root,
        $env
    );
    if (!is_resource($process)) {
        throw new RuntimeException('Could not start the seed process.');
    }
    $status = proc_close($process);
    $output = (string) file_get_contents($log);
    @unlink($log);

    return ['status' => $status, 'output' => $output];
}

$pgPort = (int) (getenv('NIZAM_PG_PORT') ?: 0);
$driver = $pgPort > 0 ? 'pgsql' : 'mysql';

if ($driver === 'pgsql') {
    $sourceConfig = [
        'driver' => 'pgsql',
        'host' => getenv('NIZAM_PG_HOST') ?: '127.0.0.1',
        'port' => $pgPort,
        'database' => 'postgres',
        'username' => getenv('NIZAM_PG_USER') ?: 'postgres',
        'password' => getenv('NIZAM_PG_PASSWORD') ?: '',
        'charset' => 'utf8mb4',
    ];
} else {
    $sourceConfig = require $root . '/config/config.php';
    if ((string) ($sourceConfig['driver'] ?? 'mysql') !== 'mysql') {
        fwrite(STDERR, "BLOCKED: set NIZAM_PG_PORT to run against PostgreSQL, or keep the MySQL config.\n");
        exit(2);
    }
}

$database = 'nizam_seed_test_' . bin2hex(random_bytes(4));
$tempPath = sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'nizam-seed-' . bin2hex(random_bytes(4));
$adminDsn = $driver === 'pgsql'
    ? sprintf('pgsql:host=%s;port=%d;dbname=postgres', $sourceConfig['host'], (int) $sourceConfig['port'])
    : sprintf('mysql:host=%s;port=%d;charset=%s', $sourceConfig['host'], (int) $sourceConfig['port'], $sourceConfig['charset'] ?? 'utf8mb4');

$basePdo = new PDO($adminDsn, $sourceConfig['username'], $sourceConfig['password'], [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
]);

$logTail = static function (string $output, int $lines = 30): string {
    $rows = preg_split('/\r?\n/', trim($output)) ?: [];
    return implode("\n", array_slice($rows, -$lines));
};

try {
    foreach (['config', 'storage/logs', 'storage/uploads'] as $dir) {
        $path = $tempPath . DIRECTORY_SEPARATOR . $dir;
        if (!mkdir($path, 0777, true) && !is_dir($path)) {
            throw new RuntimeException("Could not create {$path}.");
        }
    }
    $testConfig = $sourceConfig;
    $testConfig['database'] = $database;
    file_put_contents(
        $tempPath . DIRECTORY_SEPARATOR . 'config/config.php',
        "<?php\n// Generated by tests/official-seed.php. Not committed.\nreturn " . var_export($testConfig, true) . ";\n"
    );

    if ($driver === 'pgsql') {
        $basePdo->exec('CREATE DATABASE "' . $database . '"');
        $testDsn = sprintf(
            'pgsql:host=%s;port=%d;dbname=%s',
            $sourceConfig['host'],
            (int) $sourceConfig['port'],
            $database
        );
    } else {
        $basePdo->exec("CREATE DATABASE `{$database}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $testDsn = sprintf(
            'mysql:host=%s;port=%d;dbname=%s;charset=%s',
            $sourceConfig['host'],
            (int) $sourceConfig['port'],
            $database,
            $sourceConfig['charset'] ?? 'utf8mb4'
        );
    }

    $pdoOptions = [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ];
    if ($driver === 'mysql') {
        $pdoOptions[PDO::ATTR_EMULATE_PREPARES] = false;
    }
    $pdo = new PDO($testDsn, $sourceConfig['username'], $sourceConfig['password'], $pdoOptions);

    echo "Official school data seed ({$driver})\n";
    echo str_repeat('=', 60) . "\n";

    $migrationsDir = $root . '/database/' . ($driver === 'pgsql' ? 'migrations-pg' : 'migrations');
    $seedsDir = $root . '/database/' . ($driver === 'pgsql' ? 'seeds-pg' : 'seeds');

    $migrations = (new MigrationService())->run($pdo, $migrationsDir);
    seedCheck($migrations['failure'] === null, 'Migrations apply to a fresh database');

    $seeds = (new SeedService())->run($pdo, $seedsDir);
    seedCheck($seeds['failure'] === null, 'Reference seeds apply to a fresh database');

    // Pin the official calendar. The generic seed derives the current year
    // from today's date; the school package is the fixed 2026/2027 year.
    $pdo->exec("UPDATE academic_years SET is_active = 0, is_closed = 0");
    $existingYear = $pdo->query("SELECT id FROM academic_years WHERE label = '2026/2027' LIMIT 1")->fetchColumn();
    if ($existingYear === false) {
        $pdo->prepare(
            "INSERT INTO academic_years (label, start_date, end_date, is_active, is_closed, expected_weekly_capacity)
             VALUES ('2026/2027', '2026-09-01', '2027-06-30', 1, 0, 35)"
        )->execute();
    } else {
        $pdo->prepare("UPDATE academic_years SET is_active = 1, is_closed = 0 WHERE id = :id")
            ->execute(['id' => (int) $existingYear]);
    }
    $yearId = (int) $pdo->query("SELECT id FROM academic_years WHERE label = '2026/2027' LIMIT 1")->fetchColumn();

    $markerOne = $tempPath . '/storage/official-data-seed.json';
    $first = runSeedCommand(
        [$root . '/bin/seed-official-data.php', '--marker=' . $markerOne],
        $tempPath
    );
    seedCheck($first['status'] === 0, 'The seed command succeeds on a fresh database', $logTail($first['output']));
    if ($first['status'] !== 0) {
        echo $logTail($first['output'], 60) . "\n";
        throw new RuntimeException('Seed command failed.');
    }

    $count = static fn (string $sql): int => (int) $pdo->query($sql)->fetchColumn();
    $counts = [
        'classes' => $count('SELECT COUNT(*) FROM classes WHERE academic_year_id = ' . $yearId),
        'students' => $count('SELECT COUNT(*) FROM students'),
        'enrollments' => $count('SELECT COUNT(*) FROM student_enrollments WHERE academic_year_id = ' . $yearId),
        'teachers' => $count('SELECT COUNT(*) FROM teachers'),
        'subjects' => $count('SELECT COUNT(*) FROM subjects'),
        'timetables' => $count('SELECT COUNT(*) FROM timetables WHERE academic_year_id = ' . $yearId),
        'assessments' => $count('SELECT COUNT(*) FROM assessment_schedules WHERE academic_year_id = ' . $yearId),
        'gender_confirmed' => $count('SELECT COUNT(*) FROM students WHERE gender IS NOT NULL'),
        'religion_confirmed' => $count('SELECT COUNT(*) FROM students WHERE religion IS NOT NULL'),
        'second_language_confirmed' => $count('SELECT COUNT(*) FROM students WHERE second_language IS NOT NULL'),
    ];

    foreach ($counts as $name => $value) {
        echo "  info  {$name}: {$value}\n";
    }

    seedCheck($counts['classes'] === 17, 'Exactly 17 official classes exist', (string) $counts['classes']);
    seedCheck($counts['students'] === 778, 'Exactly 778 populated source students exist', (string) $counts['students']);
    seedCheck($counts['enrollments'] === 778, 'Exactly 778 active enrollments exist', (string) $counts['enrollments']);
    seedCheck($counts['subjects'] === 17, 'The 17-subject catalogue is complete', (string) $counts['subjects']);
    seedCheck($counts['timetables'] === 507, 'Exactly 507 timetable slots exist', (string) $counts['timetables']);
    seedCheck($counts['assessments'] === 45, 'Exactly 45 assessment rows exist', (string) $counts['assessments']);
    seedCheck($counts['teachers'] >= 29, 'The printed teachers were created', (string) $counts['teachers']);
    seedCheck($counts['gender_confirmed'] === 778, 'Every source student has the reviewed roster gender', (string) $counts['gender_confirmed']);
    seedCheck($counts['religion_confirmed'] === 778, 'All 778 students now carry a religion (703 source-backed + 75 name-inferred)', (string) $counts['religion_confirmed']);
    seedCheck($counts['second_language_confirmed'] === 424, 'Exactly 424 second-language values are proved by the source', (string) $counts['second_language_confirmed']);
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE gender_source = 'official_roster_layout'") === 778,
        'Every reviewed gender carries official-roster provenance'
    );
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE religion_source = 'official_roster_rule_v2'") === 703,
        'Every confirmed religion carries the versioned source rule'
    );
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE religion IS NULL") === 0,
        'No religion remains explicitly unconfirmed after name inference'
    );
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE second_language_source IN ('printed_cell', 'class_heading')") === 424,
        'Every second language records printed-cell or class-heading evidence'
    );
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE full_name = 'ريماس فاروق اسماعيل حسن'") === 1,
        'The populated B5 L17 source row is restored exactly once'
    );
    seedCheck(
        $count("SELECT COUNT(*) FROM students WHERE date_of_birth IS NOT NULL") === 0,
        'The source does not fabricate any birth date'
    );

    $classNames = $pdo->query('SELECT name FROM classes WHERE academic_year_id = ' . $yearId . ' ORDER BY name')
        ->fetchAll(PDO::FETCH_COLUMN);
    $expectedClasses = [];
    for ($number = 1; $number <= 9; $number++) {
        $expectedClasses[] = 'A' . $number;
    }
    for ($number = 1; $number <= 8; $number++) {
        $expectedClasses[] = 'B' . $number;
    }
    sort($expectedClasses);
    seedCheck($classNames === $expectedClasses, 'A1-A9 and B1-B8 are all present', implode(',', $classNames));

    $pathwayCount = $count("SELECT COUNT(*) FROM classes WHERE academic_year_id = {$yearId} AND pathway_ar IS NOT NULL AND pathway_ar <> ''");
    seedCheck($pathwayCount === 17, 'Every class carries its official Arabic pathway label', (string) $pathwayCount);

    $capacityCount = $count("SELECT COUNT(*) FROM classes WHERE academic_year_id = {$yearId} AND capacity = 50");
    seedCheck($capacityCount === 17, 'All 17 official classes carry the school-confirmed 50-student capacity', (string) $capacityCount);

    $marker = is_file($markerOne) ? json_decode((string) file_get_contents($markerOne), true) : null;
    seedCheck(is_array($marker) && ($marker['academic_year'] ?? '') === '2026/2027', 'The seed marker records the official year');
    seedCheck(is_array($marker) && (int) ($marker['official_data_version'] ?? 0) === 5, 'The marker records reviewed data version 5');
    seedCheck(is_array($marker) && (int) ($marker['counts']['students_in_year'] ?? 0) === 778, 'The marker records the verified student count');

    // Second run with a different marker: exercises the importers' own
    // idempotency rather than the marker shortcut.
    $second = runSeedCommand(
        [$root . '/bin/seed-official-data.php', '--force', '--marker=' . $tempPath . '/storage/second-seed.json'],
        $tempPath
    );
    seedCheck($second['status'] === 0, 'A forced second seed succeeds', $logTail($second['output']));

    $after = [
        'classes' => $count('SELECT COUNT(*) FROM classes WHERE academic_year_id = ' . $yearId),
        'students' => $count('SELECT COUNT(*) FROM students'),
        'enrollments' => $count('SELECT COUNT(*) FROM student_enrollments WHERE academic_year_id = ' . $yearId),
        'timetables' => $count('SELECT COUNT(*) FROM timetables WHERE academic_year_id = ' . $yearId),
        'assessments' => $count('SELECT COUNT(*) FROM assessment_schedules WHERE academic_year_id = ' . $yearId),
        'subjects' => $count('SELECT COUNT(*) FROM subjects'),
        'teachers' => $count('SELECT COUNT(*) FROM teachers'),
    ];
    seedCheck($after['classes'] === $counts['classes'], 'A second run creates no duplicate classes', (string) $after['classes']);
    seedCheck($after['students'] === $counts['students'], 'A second run creates no duplicate students', (string) $after['students']);
    seedCheck($after['enrollments'] === $counts['enrollments'], 'A second run creates no duplicate enrollments', (string) $after['enrollments']);
    seedCheck($after['timetables'] === $counts['timetables'], 'A second run creates no duplicate timetable slots', (string) $after['timetables']);
    seedCheck($after['assessments'] === $counts['assessments'], 'A second run creates no duplicate assessments', (string) $after['assessments']);
    seedCheck($after['subjects'] === $counts['subjects'], 'A second run creates no duplicate subjects', (string) $after['subjects']);
    seedCheck($after['teachers'] === $counts['teachers'], 'A second run creates no duplicate teachers', (string) $after['teachers']);

    // A normal boot with a marker present must not import at all.
    $third = runSeedCommand([$root . '/bin/seed-official-data.php'], $tempPath);
    seedCheck($third['status'] === 0, 'A boot with the marker present is a clean no-op', $logTail($third['output']));
    seedCheck(
        str_contains($third['output'], 'already seeded') && !str_contains($third['output'], '==>'),
        'The marker short-circuits before any importer runs'
    );

    $activeEnrollments = $count("SELECT COUNT(*) FROM student_enrollments WHERE academic_year_id = {$yearId} AND status = 'active'");
    seedCheck($activeEnrollments === 778, 'All seeded enrollments are active', (string) $activeEnrollments);
} catch (Throwable $e) {
    fwrite(STDERR, 'BLOCKED: ' . $e->getMessage() . "\n");
    $failed++;
} finally {
    $pdo = null;
    try {
        if (isset($basePdo)) {
            $basePdo->exec($driver === 'pgsql'
                ? 'DROP DATABASE IF EXISTS "' . $database . '"'
                : "DROP DATABASE IF EXISTS `{$database}`");
        }
    } catch (Throwable) {
        // Best effort cleanup.
    }
    if (is_dir($tempPath)) {
        $items = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($tempPath, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST
        );
        foreach ($items as $item) {
            $item->isDir() ? @rmdir($item->getPathname()) : @unlink($item->getPathname());
        }
        @rmdir($tempPath);
    }
}

echo "\n{$passed} passed, {$failed} failed.\n";
exit($failed === 0 ? 0 : 1);
